"""
=============================================================================
STAGE 2 - MISSION 1 : 어제 그 사건의 현장 검증
=============================================================================
어제 STAGE 1에서 우리는 두 가지 미스터리를 남겼습니다.

  미스터리 ①
    영어 전용 모델에 한국어 뉴스를 넣었더니 POSITIVE 0.8022 가 나왔다.
    "한국어가 의미 없는 조각으로 부서진다"고 제가 설명했죠.
    → 오늘 그 조각들을 직접 눈으로 봅니다.

  미스터리 ②
    "이 제품은 품질이 좋지 않아 추천하기 어렵습니다." 가 3점(중립)으로 샜다.
    "'좋'이라는 긍정 신호가 살아남았을 것"이라고 추측했죠.
    → 오늘 그 추측이 맞는지 검증합니다.

★ 이 파일은 모델을 로드하지 않습니다. 토크나이저만 씁니다(수 MB, 매우 빠름).

실행 : python 01_see_the_breakage.py
=============================================================================
"""

from transformers import AutoTokenizer
import warnings
warnings.filterwarnings("ignore")
import logging
logging.getLogger("transformers").setLevel(logging.ERROR)


# -----------------------------------------------------------------------------
# 비교할 토크나이저 2종
# -----------------------------------------------------------------------------
# AutoTokenizer : 모델 이름만 주면 그 모델에 맞는 토크나이저를 자동으로 가져옵니다.
#                 (어제 배운 "tokenizer 인자는 생략이 안전하다"의 정체가 이것입니다)
TOKENIZERS = [
    (
        "🔴 영어 전용",
        "distilbert-base-uncased",
        "어제 한국어 뉴스를 POSITIVE라고 답한 그 모델의 토크나이저",
    ),
    (
        "🔵 다국어",
        "bert-base-multilingual-cased",
        "104개 언어 지원. 한국어 사전이 들어 있음",
    ),
]


def show(tok, text, label=""):
    """문장 하나를 토큰화해서 조각과 ID를 보기 좋게 출력합니다."""
    # tokenize()  : 특수토큰 없이 순수한 조각만 봅니다 (지금은 이게 목적)
    # encode()    : [CLS] ... [SEP] 까지 붙은 최종 ID를 봅니다 (MISSION 3에서 다룸)
    tokens = tok.tokenize(text)
    ids = tok.convert_tokens_to_ids(tokens)

    unk_token = tok.unk_token                     # 보통 "[UNK]"
    unk_count = tokens.count(unk_token)

    print(f"\n  {label}입력   : {text}")
    print(f"  조각 수 : {len(tokens)}개")
    print(f"  조각    : {tokens}")
    print(f"  ID      : {ids}")

    if unk_count:
        ratio = unk_count / len(tokens) * 100
        print(f"  🚨 [UNK] : {unk_count}개 ({ratio:.0f}%) — 사전에 없어서 버려진 조각")
    return tokens


# =============================================================================
# 실험 1 : 한국어 뉴스 문장이 어떻게 부서지는가
# =============================================================================
print("=" * 78)
print("실험 1 — 어제 POSITIVE 0.8022 가 나온 그 문장")
print("=" * 78)

NEWS = "오늘 주식시장은 투자자들의 불안으로 인해 큰 폭으로 하락했습니다."

for name, model_id, desc in TOKENIZERS:
    print(f"\n{'-' * 78}")
    print(f"{name}  ({model_id})")
    print(f"  {desc}")
    tok = AutoTokenizer.from_pretrained(model_id)
    show(tok, NEWS)


# =============================================================================
# 실험 2 : 같은 토크나이저로 영어를 넣으면?  (대조군)
# =============================================================================
print("\n\n" + "=" * 78)
print("실험 2 — 대조군: 영어 토크나이저에 영어를 넣으면")
print("=" * 78)

ENG = "The stock market dropped sharply due to investor anxiety."

tok_en = AutoTokenizer.from_pretrained("distilbert-base-uncased")
show(tok_en, ENG, label="(영어) ")


# =============================================================================
# 실험 3 : ★ 핵심 — "좋지 않아" 에서 '좋'은 살아남는가
# =============================================================================
print("\n\n" + "=" * 78)
print("실험 3 — 어제 3점(중립)으로 샌 문장의 해부")
print("=" * 78)

LEAKED = "이 제품은 품질이 좋지 않아 추천하기 어렵습니다."

# 어제 이 문장을 실제로 판정한 모델의 토크나이저를 씁니다.
tok_multi = AutoTokenizer.from_pretrained(
    "nlptown/bert-base-multilingual-uncased-sentiment"
)
tokens = show(tok_multi, LEAKED, label="(문제의 문장) ")

# '좋' 이라는 글자가 어떤 조각 안에 살아 있는지 찾아봅니다.
print("\n  🔍 '좋' 글자 추적:")
found = [t for t in tokens if "좋" in t]
if found:
    print(f"     발견! → {found}")
    print("     ★ 부정 어미(않아)와 분리된 채 긍정 신호를 그대로 들고 있습니다.")
else:
    print("     '좋'이 독립 조각으로 남아있지 않습니다. 다른 설명이 필요합니다.")

# 비교군: 부정어가 없는 순수 긍정문
print("\n  [비교] 부정어가 없는 순수 긍정문:")
show(tok_multi, "이 제품은 품질이 좋습니다.", label="")


