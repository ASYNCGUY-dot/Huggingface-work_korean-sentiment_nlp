"""
=============================================================================
STAGE 1 - MISSION 3 : 모델 배틀 — 베이스 모델의 정체를 폭로하다
=============================================================================
목표 : "LABEL_0 / LABEL_1" 이 나오는 이유를 직접 눈으로 확인한다.
       이게 1일차에서 가장 헷갈리는 부분입니다.

핵심 개념:
    베이스 모델      = 언어를 '이해'하는 능력만 있음. 분류 기준이 없음.
    파인튜닝된 모델  = 특정 업무(감정 분류 등)까지 학습 완료.

실행 : python 03_model_battle.py
=============================================================================
"""

from transformers import pipeline
import warnings
import logging

# =============================================================================
# ★ 스위치 : 베이스 모델의 "분류기 새로 만들었음" 경고를 볼 것인가?
# =============================================================================
#   False → 화면이 깔끔함 (경고 숨김)
#   True  → 아래 경고가 그대로 보입니다. 이게 베이스 모델의 결정적 증거입니다.
#
#     Some weights of RobertaForSequenceClassification were not initialized
#     ... and are newly initialized: ['classifier.dense.weight', ...]
#     You should probably TRAIN this model on a down-stream task
#
#   → 한 번은 True 로 바꿔서 눈으로 보세요. 그 다음 다시 False 로.
SHOW_INIT_WARNING = False

if not SHOW_INIT_WARNING:
    warnings.filterwarnings("ignore")
    logging.getLogger("transformers").setLevel(logging.ERROR)


# -----------------------------------------------------------------------------
# [1] 명확하게 긍정인 문장 — 사람이라면 100% 긍정이라고 답할 문장
# -----------------------------------------------------------------------------
TEXTS = [
    "오늘 날씨가 너무 좋아서 기분이 상쾌합니다.",   # 명백한 긍정
    "이번 결과는 정말 실망스럽습니다.",             # 명백한 부정
]


# -----------------------------------------------------------------------------
# [2] 대결 카드
# -----------------------------------------------------------------------------
# task 도 함께 지정합니다.
#   sentiment-analysis 와 text-classification 은 사실 같은 파이프라인입니다.
#   (sentiment-analysis 가 text-classification 의 별칭입니다)
FIGHTERS = [
    {
        "name": "🔴 베이스 모델 (klue/roberta-base)",
        "model": "klue/roberta-base",
        "task": "text-classification",
        "type": "BASE",
    },
    {
        "name": "🔵 파인튜닝 모델 (nlptown 다국어 감정)",
        "model": "nlptown/bert-base-multilingual-uncased-sentiment",
        "task": "sentiment-analysis",
        "type": "FINETUNED",
    },
]


# -----------------------------------------------------------------------------
# [3] 배틀 시작
# -----------------------------------------------------------------------------
for fighter in FIGHTERS:
    print("\n" + "=" * 78)
    print(fighter["name"])
    print("=" * 78)

    try:
        clf = pipeline(fighter["task"], model=fighter["model"], framework="pt")

        # ---------------------------------------------------------------
        # ★ 이 모델은 선택지가 몇 개인가? (랜덤 기준선 계산용)
        # ---------------------------------------------------------------
        # 2지선다면 찍어도 0.50 / 5지선다면 찍어도 0.20 이 나옵니다.
        # 따라서 "점수가 낮다"의 기준은 모델마다 달라야 합니다.
        num_labels = clf.model.config.num_labels
        baseline = 1 / num_labels

        print(f"  선택지 : {num_labels}개  (찍었을 때 기대 점수 = {baseline:.2f})")

        scores_seen = []  # 문장별 점수를 모아서 나중에 비교

        for text in TEXTS:
            result = clf(text)[0]
            label = result["label"]
            score = result["score"]
            scores_seen.append(score)

            # 랜덤 기준선의 몇 배인가 → 모델 간 공정 비교의 핵심 지표
            ratio = score / baseline

            print(f"\n  입력 : {text}")
            print(f"  라벨 : {label}")
            print(f"  점수 : {score:.4f}   (기준선의 {ratio:.2f}배)")

            # ---------------------------------------------------------------
            # 진단 ① 라벨 이름이 LABEL_숫자 형태 → 분류 레이어가 학습되지 않음
            # ---------------------------------------------------------------
            if label.upper().startswith("LABEL_"):
                print("  진단 : ⚠️  라벨에 이름이 없습니다 → 파인튜닝되지 않은 베이스 모델")

            # ---------------------------------------------------------------
            # 진단 ② 랜덤 기준선 대비 배율로 판정
            # ---------------------------------------------------------------
            # (수정 이력 2026-08-05)
            #   이전 버전은 "0.45~0.70이면 경고"라는 고정 구간을 썼습니다.
            #   그건 2지선다 모델 기준이라, 5지선다 모델의 0.62처럼
            #   충분히 좋은 점수까지 잘못 경고하는 버그가 있었습니다.
            #   → 클래스 개수를 반영한 배율 방식으로 교체했습니다.
            if ratio < 1.5:
                print("  진단 : ⚠️  기준선의 1.5배 미만 → 사실상 찍은 수준입니다")
            elif ratio < 2.5:
                print("  진단 : 🟡 애매한 구간 → 모델이 판단은 하지만 확신은 약합니다")
            else:
                print("  진단 : ✅ 기준선 대비 충분히 높음 → 신뢰할 만합니다")

        # ---------------------------------------------------------------
        # 진단 ③ 정반대 문장인데 점수가 거의 같은가? ← 결정적 증거
        # ---------------------------------------------------------------
        if len(scores_seen) >= 2:
            gap = abs(scores_seen[0] - scores_seen[1])
            print(f"\n  ▶ 두 문장의 점수 차이 : {gap:.4f}")
            if gap < 0.05:
                print("    🚨 정반대 뜻의 문장인데 점수가 거의 같습니다.")
                print("       = 모델이 '문장을 읽고 판단'한 게 아니라는 결정적 증거입니다.")
            else:
                print("    ✅ 두 문장을 서로 다르게 인식하고 있습니다.")

    except Exception as e:
        print(f"  ✖ 실행 실패: {type(e).__name__} - {e}")

print("\n" + "=" * 78)


# =============================================================================
# 🎓 해설 — 왜 베이스 모델은 LABEL_0을 뱉는가
# =============================================================================
#
# 모델의 구조는 크게 두 부분입니다.
#
#     ┌─────────────────────────┐
#     │   인코더 (Encoder)       │  ← 한국어를 이해하는 부분. 사전학습 완료 ✅
#     ├─────────────────────────┤
#     │   분류 헤드 (Classifier) │  ← 최종 판단을 내리는 부분
#     └─────────────────────────┘
#
# klue/roberta-base 는 인코더만 학습되어 있습니다.
# 분류 헤드는 pipeline이 실행되는 순간 **랜덤 숫자로 새로 만들어집니다.**
#
# 실행할 때 이런 경고를 보셨을 겁니다:
#   "Some weights ... are newly initialized: ['classifier.bias', 'classifier.weight']
#    You should probably TRAIN this model on a down-stream task"
#
# 번역하면: "분류기를 새로 만들었어. 학습시키고 써." 라는 뜻입니다.
#
# 랜덤 가중치로 판단하니:
#   - 라벨에 이름이 없음 → LABEL_0, LABEL_1 자동 생성
#   - 확률이 0.5 근처에서 애매하게 나옴
#
# 이건 모델이 고장난 게 아닙니다. **사용법이 틀린 것**입니다.
#
# -----------------------------------------------------------------------------
# ✅ 베이스 모델을 제대로 쓰는 2가지 방법
# -----------------------------------------------------------------------------
#  방법 1) 이미 파인튜닝된 모델을 찾아 쓴다  ← 지금 단계에서 할 일
#          예: daekeun-ml/koelectra-small-v3-nsmc (한국어 영화리뷰 감정)
#
#  방법 2) 내가 직접 파인튜닝한다  ← 3일차(STAGE 3)에서 배웁니다
#          베이스 모델 + 내 데이터 + Trainer → 나만의 모델
