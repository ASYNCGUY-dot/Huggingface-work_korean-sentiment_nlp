from transformers import pipeline

# 경고 메시지가 너무 많이 뜨면 눈이 아프니 줄여줍니다.
# (에러가 아니라 경고이므로 숨겨도 안전합니다)
import warnings
warnings.filterwarnings("ignore")

import logging
logging.getLogger("transformers").setLevel(logging.ERROR)


# -----------------------------------------------------------------------------
# [1] 테스트할 한국어 문장
# -----------------------------------------------------------------------------
TEST_TEXT = "오늘 주식시장은 투자자들의 불안으로 인해 큰 폭으로 하락했습니다."


# -----------------------------------------------------------------------------
# [2] 비교할 모델 목록
# -----------------------------------------------------------------------------
# (별명, 모델경로, 설명) 튜플의 리스트로 관리합니다.
# None 은 "모델을 지정하지 않음"을 뜻합니다.
MODELS = [
    (
        "① 모델 미지정 (기본값)",
        None,
        "허깅페이스가 영어 전용 모델을 자동 선택합니다. 한국어를 학습한 적이 없습니다.",
    ),
    (
        "② 다국어 별점 모델",
        "nlptown/bert-base-multilingual-uncased-sentiment",
        "1~5 stars 로 반환. 한국어 포함 다국어 지원. 범용적이지만 도메인 전문성은 낮음.",
    ),
    (
        "③ 한국어 금융 특화 모델",
        "snunlp/KR-FinBert-SC",
        "한국어 금융 뉴스로 학습. 단, '감정'이 아니라 '주가 영향 방향성'을 예측합니다.",
    ),
]


# -----------------------------------------------------------------------------
# [3] 하나씩 돌려보기
# -----------------------------------------------------------------------------
print("=" * 78)
print(f"테스트 문장 : {TEST_TEXT}")
print("=" * 78)

for name, model_id, description in MODELS:
    print(f"\n{name}")
    print(f"  모델   : {model_id if model_id else '(지정 안 함 → 자동 선택)'}")
    print(f"  설명   : {description}")

    try:
        # model 인자가 None이면 아예 전달하지 않습니다.
        # → 허깅페이스가 기본 모델을 자동으로 고릅니다.
        if model_id is None:
            clf = pipeline("sentiment-analysis", framework="pt")
        else:
            clf = pipeline("sentiment-analysis", model=model_id, framework="pt")

        result = clf(TEST_TEXT)[0]

        print(f"  ▶ 결과 : {result['label']}")
        print(f"  ▶ 점수 : {round(result['score'], 4)}")

    except Exception as e:
        # 모델 다운로드 실패(네트워크 문제 등)를 대비한 안전장치
        print(f"  ✖ 실행 실패: {type(e).__name__} - {e}")
        print("    (인터넷 연결 또는 모델 이름을 확인하세요)")

print("\n" + "=" * 78)


