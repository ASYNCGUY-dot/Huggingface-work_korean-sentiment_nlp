# ① 모델 미지정
#    자동 선택되는 모델: distilbert-base-uncased-finetuned-sst-2-english
#    → 영어 영화 리뷰 데이터로만 학습된 모델입니다.
#    → 한국어를 넣으면 모델은 "모르는 글자 덩어리"를 보고 아무 답이나 냅니다.
#    → "하락했습니다"라는 명백한 부정 문장에 POSITIVE가 나올 수 있습니다.
#
# ② 다국어 모델
#    한국어를 이해합니다. 1~5 stars로 답합니다.
#    해석법: 1~2 stars = 부정 / 3 stars = 중립 / 4~5 stars = 긍정
#
# ③ 한국어 금융 모델
#    ★★ 여기서 아주 중요한 개념이 나옵니다.
#    이 모델의 "positive/negative"는 사람의 기분이 아닙니다.
#      positive → 주가 상승에 긍정적 영향
#      negative → 주가 하락에 부정적 영향
#      neutral  → 방향성 불확실
#    즉 같은 단어라도 모델마다 라벨의 정의가 다릅니다.
#    → 모델 카드(허깅페이스 모델 페이지)를 반드시 읽어야 하는 이유입니다.
#
# -----------------------------------------------------------------------------
# 💡 실무 규칙 3가지
# -----------------------------------------------------------------------------
#  1. model 인자는 항상 명시한다. 생략하면 무슨 모델이 붙을지 모른다.
#  2. 모델의 학습 언어 / 학습 도메인을 확인한다.
#  3. 라벨의 "의미"를 모델 카드에서 확인한다. POSITIVE가 항상 '기분 좋음'은 아니다.
