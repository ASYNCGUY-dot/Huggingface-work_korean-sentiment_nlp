"""
=============================================================================
STAGE 1 - MISSION 1 : 첫 번째 AI 모델 실행하기
=============================================================================
목표 : pipeline() 3줄로 감정 분석 AI를 돌려본다.
소요 : 첫 실행은 모델 다운로드 때문에 1~3분 (2회차부터는 몇 초)

실행 방법 (VS Code 터미널):
    python 01_first_pipeline.py
=============================================================================
"""

# -----------------------------------------------------------------------------
# [1] 라이브러리 불러오기
# -----------------------------------------------------------------------------
# pipeline : 허깅페이스의 "고수준 API".
#   모델 다운로드 → 토크나이저 로드 → 텐서 변환 → 추론 → 후처리
#   이 5단계를 전부 자동으로 처리해줍니다.
#   나중에 3일차에서 이 단계를 손으로 하나씩 분해하게 됩니다.
from transformers import pipeline


# -----------------------------------------------------------------------------
# [2] 파이프라인 생성
# -----------------------------------------------------------------------------
# 인자 3개의 의미:
#   task    : 무슨 일을 시킬 건가 ("sentiment-analysis" = 감정 분석)
#   model   : 어떤 모델을 쓸 건가  ← ★ 이걸 생략하면 사고가 납니다 (MISSION 2에서 확인)
#   framework: 어떤 딥러닝 엔진으로 돌릴 건가 ("pt" = PyTorch)
#
# 모델 이름 뜯어보기:  distilbert-base-uncased-finetuned-sst-2-english
#   distilbert  : BERT를 40% 가볍게 압축한 모델
#   base        : 크기 등급 (base < large)
#   uncased     : 대소문자 구분 안 함 (Apple = apple)
#   finetuned-sst-2 : SST-2(영화 리뷰) 데이터로 감정 분류 학습 완료
#   english     : 영어 전용   ← ★ 이 단어를 꼭 기억하세요
print("모델을 불러오는 중입니다... (첫 실행은 다운로드 때문에 시간이 걸립니다)")

classifier = pipeline(
    "sentiment-analysis",
    model="distilbert-base-uncased-finetuned-sst-2-english",
    framework="pt",
)

print("모델 로드 완료!\n")


# -----------------------------------------------------------------------------
# [3] 분석할 문장 준비
# -----------------------------------------------------------------------------
# 리스트로 넣으면 여러 문장을 한 번에(배치로) 처리합니다.
# 한 문장씩 반복문 돌리는 것보다 훨씬 빠릅니다.
sentences = [
    "I love using Hugging Face transformers!",   # 강한 긍정
    "That is wonderful magic!",                  # 강한 긍정
    "This is the worst product I have ever bought.",  # 강한 부정
    "The movie was okay, nothing special.",      # 애매함 ← 점수를 주목하세요
    "It works, but the price is too high.",      # 복합 감정 ← 점수를 주목하세요
]


# -----------------------------------------------------------------------------
# [4] 추론 실행
# -----------------------------------------------------------------------------
# 반환값은 리스트 안에 딕셔너리:
#   [{'label': 'POSITIVE', 'score': 0.9971}, ...]
results = classifier(sentences)


# -----------------------------------------------------------------------------
# [5] 결과 출력
# -----------------------------------------------------------------------------
print("=" * 70)
print("감정 분석 결과")
print("=" * 70)

# zip() : 두 리스트를 짝지어서 동시에 꺼냅니다.
for sentence, result in zip(sentences, results):
    label = result["label"]     # POSITIVE 또는 NEGATIVE
    score = result["score"]     # 0.0 ~ 1.0 사이의 확률

    # 점수를 시각적으로 보여주는 막대 (점수 × 20칸)
    bar = "█" * int(score * 20)

    print(f"\n문장   : {sentence}")
    print(f"감성   : {label}")
    print(f"신뢰도 : {score:.4f}  {bar}")

    # ★ 실무 감각: 점수가 0.7 미만이면 모델이 헷갈리고 있다는 뜻
    if score < 0.70:
        print("       ⚠️  신뢰도가 낮습니다. 이 결과는 믿지 마세요.")

print("\n" + "=" * 70)


# =============================================================================
# 🎯 미션 확인 사항
# =============================================================================
# 1. 4번, 5번 문장("okay, nothing special", "price is too high")의 점수를 보세요.
#
#    ※ 실측 결과 (2026-08-05, 지수님 실행):
#         4번 → NEGATIVE 0.9925
#         5번 → NEGATIVE 0.9932
#
#    애매한 문장인데도 점수가 0.99입니다. 이게 이 모델의 중요한 성질입니다.
#    → 자세한 이유는 아래 [보충 실험]에서 직접 확인하세요.
#
# 2. sentences 리스트에 본인이 만든 영어 문장 3개를 추가해서 다시 실행해보세요.
#
# 3. ★ 도전: 아래 한국어 문장을 리스트에 추가하고 실행해보세요.
#       "오늘 주식시장은 투자자들의 불안으로 큰 폭 하락했습니다."
#    결과가 어떻게 나오나요? 왜 그럴까요?
#    → 답은 MISSION 2 (02_model_matters.py)에서 확인합니다.
#
#
# =============================================================================
# 🔬 [보충 실험] 이 모델은 "모른다"고 말할 줄 모른다 — 과신(overconfidence)
# =============================================================================
# 아래 주석(''' ''')을 풀고 실행해보세요.
# 감정이 전혀 없는 사실 문장 / 이 모델이 배운 적 없는 도메인 문장을 넣습니다.
#
# 예상: "이런 건 모르겠는데?" 하고 0.5 근처가 나와야 상식적입니다.
# 실제: 그래도 0.9x 를 뱉습니다.
#
# 왜?
#   ① 이 모델은 선택지가 POSITIVE / NEGATIVE 둘뿐입니다.
#      "중립"이나 "모르겠음"이라는 출력 자체가 존재하지 않습니다.
#      객관식 2지선다에서 "답 없음"을 고를 수 없는 것과 같습니다.
#   ② 학습 방식(cross-entropy) 특성상 이런 모델은 구조적으로 과신합니다.
#      이를 "캘리브레이션(calibration)이 안 맞는다"고 합니다.
#
# ★ 실무 교훈:
#   "점수가 높다 = 정답이다" 가 아닙니다.
#   "점수가 높다 = 모델이 자기 기준에서 확신한다" 일 뿐입니다.
#   그 기준이 내 문제와 맞는지는 사람이 판단해야 합니다.
# =============================================================================


print("\n" + "=" * 70)
print("[보충 실험] 감정이 없는 문장에도 확신할까?")
print("=" * 70)

neutral_texts = [
    "The meeting is scheduled for 3 PM.",        # 단순 사실 — 감정 없음
    "Water boils at 100 degrees Celsius.",       # 과학 상식 — 감정 없음
    "The patient's white blood cell count is 7.2.",  # 의료 도메인 — 학습 안 된 영역
    "asdf qwer zxcv",                            # 의미 없는 문자열
]

for text, res in zip(neutral_texts, classifier(neutral_texts)):
    print(f"\n문장   : {text}")
    print(f"감성   : {res['label']}")
    print(f"신뢰도 : {res['score']:.4f}")
    if res["score"] > 0.9:
        print("       🚨 감정이 없는 문장인데 0.9 이상! → 이게 '과신'입니다.")


